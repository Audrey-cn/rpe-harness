from pathlib import Path
import json,hashlib,sys,subprocess
from rpe_harness.evolution import cycle,record_verified_feedback,EvolutionStore
from rpe_harness.storage import RunStore
root=Path("/private/var/folders/6f/1dz7k1mx6mlbk4vwbrg2n00c0000gn/T/rpe-v12-development-20261014-fp1l7bvp")
state=root/"installed-contract-release";db=state/"runs.sqlite"
report=json.loads((state/"hermes-anchored/report.json").read_text())
accepted_ids=[]
for case in report["cases"]:
    if case["expected"]!="success" or not case["entry_accepted"] or not case["validation"]["passed"]:continue
    for run_id in case["run_ids"]:
        run=RunStore(db).get(run_id)
        if run["status"]=="succeeded" and run["source"]=="hermes":
            assert record_verified_feedback(run_id,db) is not None
            accepted_ids.append(run_id)
code=(root/"codex-candidate-2/workspace/candidate.py").read_text()
seen=[]
def proposer(context):
    selected=[item["run_id"] for item in context["verified_feedback"] if item["run_id"] in accepted_ids and item["plan"]["input_format"]=="csv"]
    seen.extend(selected)
    return ([{"component":"executor","kind":"csv_executor","content":code,"evidence_run_ids":selected}] if selected else [])
result=cycle(db,state,auto_apply=True,proposer=proposer)
versions=EvolutionStore(db).list_versions()
actual_bound=[version for version in versions if version["component"]=="executor" and set(version["evidence_run_ids"]).issubset(set(accepted_ids)) and version["evidence_run_ids"]]
output={"wheel_sha256":report["wheel_sha256"],"accepted_real_hermes_success_run_ids":accepted_ids,"generated_cli_candidate_code_sha256":hashlib.sha256(code.encode()).hexdigest(),"proposer_bound_real_csv_run_ids":seen,"cycle":result,"actual_executor_versions_bound_to_real_feedback":[{"version_id":v["version_id"],"state":v["state"],"evidence_run_ids":v["evidence_run_ids"],"validation_passed":v["validation"]["passed"]} for v in actual_bound],"interpretation":"The unattended callback reuses code generated by the earlier real isolated CLI; no additional model call or scheduled worker is claimed. Only fully accepted live sessions seed this binding. Local CLI feedback remains separately identified."}
assert seen and actual_bound and all(v['validation']['passed'] for v in actual_bound)
active=EvolutionStore(db).get_active('executor','csv_executor')
assert active and active['version_id'] in {v['version_id'] for v in actual_bound}
workspace=state/'real-feedback-followup';workspace.mkdir()
source=workspace/'orders.csv';source.write_text('id,value\n001,first\n001,later\n002,second\n')
request={'schema_version':2,'event_id':'real-feedback-upgrade-followup','capability':'tabular.deduplicate','goal':'verify actually activated executor from live feedback','constraints':['preserve_original','preserve_order'],'execution':{'input_path':str(source),'output_path':str(workspace/'out.csv'),'key_columns':['id']}}
request_file=workspace/'request.json';request_file.write_text(json.dumps(request,ensure_ascii=False,indent=2))
proc=subprocess.run([sys.executable,'-I','-B','-m','rpe_harness','run','--request',str(request_file),'--db',str(db)],cwd=workspace,capture_output=True,text=True,timeout=30)
run=json.loads(proc.stdout);assert proc.returncode==0 and run['status']=='succeeded'
assert run['artifact']['actual_executor']['candidate_version_id']==active['version_id']
assert run['artifact']['actual_executor']['code_sha256']==hashlib.sha256(code.encode()).hexdigest()
assert (workspace/'out.csv').read_text(encoding='utf-8-sig')=='id,value\n001,first\n002,second\n'
(workspace/'run.json').write_text(json.dumps(run,ensure_ascii=False,indent=2))
output['actual_followup']={'run_id':run['run_id'],'manual_truth_passed':True,'actual_executor':run['artifact']['actual_executor'],'verification':run['verification'],'source_unchanged':hashlib.sha256(source.read_bytes()).hexdigest()==run['artifact']['input_sha256']}
assert output['actual_followup']['source_unchanged']
(state/"real-feedback-evolution.json").write_text(json.dumps(output,ensure_ascii=False,indent=2))
print(json.dumps({"accepted_real_hermes_feedback":len(accepted_ids),"real_csv_proposer_feedback":len(seen),"whole_architecture_proposals":result["proposal_count"],"actual_bound_versions":len(actual_bound)},ensure_ascii=False))
