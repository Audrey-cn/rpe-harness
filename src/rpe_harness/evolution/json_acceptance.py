def recipe_valid(recipe):
    allowed = {'capability', 'input_format', 'style', 'constraints', 'procedure'}
    if (type(recipe) is not dict or set(recipe) != allowed
            or recipe['capability'] != 'json.normalize' or recipe['input_format'] != 'json'
            or type(recipe['style']) is not str or recipe['style'] not in {'pretty', 'minify'}
            or type(recipe['constraints']) is not list
            or type(recipe['procedure']) is not list or recipe['procedure'] != _PROCEDURE):
        raise ValueError('JSON recipe cannot replace the registered execution procedure')
    canonical = json_contract.validate_constraints(recipe['constraints'])
    if list(canonical) != recipe['constraints']:
        raise ValueError('JSON recipe constraints must be canonical')


def prepare_code(plan, content, root, timeout=3.0):
    """Run candidate bytes, then stage them for the trusted independent oracle."""
    if not isinstance(plan, json_contract.JsonNormalizePlan):
        raise ValueError('JSON candidate requires an immutable JSON plan')
    source, output = json_contract.validate_paths(plan.input_path, plan.output_path)
    raw = read_source(source, max_bytes=_MAX_INPUT_BYTES)
    if digest(raw) != plan.input_sha256:
        raise ValueError('source changed after the execution plan')
    artifact = sandbox.run_candidate(content, plan.to_dict(), root, timeout=timeout)
    prepared = plan.verification_parameters()
    try:
        staging = _new_staging(source, output, plan.input_sha256)
        prepared['staging_path'] = str(staging)
        with staging.open('wb') as handle:
            handle.write(artifact)
            handle.flush()
            os.fsync(handle.fileno())
        return prepared
    except BaseException:
        cleanup_staging(prepared)
        raise


def _fixture_check(content, kind, fixture, root, timeout):
    name, split, source_bytes, style, expected, mode = fixture
    directory = Path(root) / name
    directory.mkdir()
    source, output = directory / 'source.json', directory / 'result.json'
    source.write_bytes(source_bytes)
    plan = json_contract.JsonNormalizePlan(capability='json.normalize', contract_version=1,
        executor_id=json_contract.EXECUTOR_ID, executor_revision=json_contract.EXECUTOR_REVISION,
        verifier_revision=json_contract.VERIFIER_REVISION, input_path=str(source),
        output_path=str(output), input_format='json', input_sha256=digest(source_bytes),
        style=style, constraints=('preserve_order', 'preserve_original'),
        goal='independent manual JSON candidate fixture')
    prepared, correct, rejected, invoked, oracle_passed, error = None, False, False, False, False, None
    try:
        if mode == 'admission_reject':
            # The byte budget is intentionally admission, never candidate parsing.
            request = {'schema_version': 2, 'event_id': name, 'capability': 'json.normalize',
                       'goal': plan.goal, 'constraints': list(plan.constraints),
                       'execution': {'input_path': str(source), 'output_path': str(output), 'style': style}}
            try:
                json_contract.JsonNormalizePlan.from_request(request)
            except ValueError as problem:
                rejected, error = True, str(problem)[:1200]
        elif kind == 'json_executor':
            # Do not call from_request here: invalid JSON must reach the producer.
            prepared = prepare_code(plan, content, directory.parent, timeout)
            invoked = True
        else:
            prepared = json_execution.prepare_json_normalization(**plan.execution_kwargs())
        if prepared is not None:
            report = json_verification.verify_json_normalization(prepared, plan)
            oracle_passed = report['passed'] is True
            actual = json_verification._read_artifact(prepared['staging_path'])
            correct = expected is not None and actual == expected and oracle_passed
    except sandbox.CandidateRejected as problem:
        invoked, rejected, error = True, True, str(problem)[:1200]
    except sandbox.CandidateExecutionError as problem:
        invoked, error = True, str(problem)[:1200]
    except ValueError as problem:
        # A trusted recipe producer can reject its own parsing. A parent-side
        # contract, filesystem or budget error is not an untrusted rejection.
        if kind == 'json_recipe' and mode == 'candidate_reject':
            rejected = True
        error = str(problem)[:1200]
    except (OSError, RuntimeError, UnicodeError, TypeError, KeyError) as problem:
        error = str(problem)[:1200]
    finally:
        if prepared is not None:
            cleanup_staging(prepared)
    source_safe = source.read_bytes() == source_bytes
    output_safe = not os.path.lexists(output)
    passed = source_safe and output_safe and (correct if mode == 'valid' else rejected)
    return {'fixture': name, 'split': split, 'mode': mode, 'passed': passed,
            'source_preserved': source_safe, 'output_preserved': output_safe,
            'candidate_invoked': invoked, 'rejection_observed': rejected,
            'oracle_passed': oracle_passed,
            'manual_truth_sha256': digest(expected) if expected is not None else None,
            'error': error}


def replay_acceptance(store, content, kind, timeout=3.0):
    if kind not in JSON_KINDS:
        raise ValueError('unregistered JSON candidate kind')
    if type(timeout) not in {float, int} or not 0 < timeout <= 3:
        raise ValueError('JSON acceptance timeout must be in (0,3] seconds')
    if kind == 'json_recipe':
        recipe_valid(json.loads(content))
    directory = store.owned_path(store.owned_root / 'evolution-validation')
    directory.mkdir(exist_ok=True)
    checks = []
    with tempfile.TemporaryDirectory(prefix='json-fixtures-', dir=directory) as name:
        for fixture in _FIXTURES:
            check = _fixture_check(content, kind, fixture, Path(name), timeout)
            checks.append(check)
            if check['passed'] is not True:
                break
    return checks


def complete_certificate(report):
    if (type(report) is not dict or type(report.get('kind')) is not str
            or report['kind'] not in JSON_KINDS
            or report.get('capability') != 'json.normalize'):
        return False
    checks = report.get('checks')
    if type(checks) is not list or len(checks) != len(_FIXTURES):
        return False
    for check, fixture in zip(checks, _FIXTURES):
        name, split, _, _, expected, mode = fixture
        if type(check) is not dict:
            return False
        truth = {'fixture': name, 'split': split, 'mode': mode,
                 'passed': True, 'source_preserved': True, 'output_preserved': True,
                 'candidate_invoked': report['kind'] == 'json_executor' and mode != 'admission_reject',
                 'rejection_observed': mode != 'valid', 'oracle_passed': mode == 'valid',
                 'manual_truth_sha256': digest(expected) if expected is not None else None}
        if any(key not in check or type(check[key]) is not type(value) or check[key] != value
               for key, value in truth.items()):
            return False
    limits, expected_limits = report.get('resource_limits'), sandbox.resource_limits('json.normalize')
    return (type(report.get('train_count')) is int
            and report['train_count'] == sum(case[1] == 'train' for case in _FIXTURES)
            and type(report.get('heldout_count')) is int
            and report['heldout_count'] == sum(case[1] == 'heldout' for case in _FIXTURES)
            and type(limits) is dict and set(limits) == set(expected_limits)
            and all(type(limits[key]) is type(value) and limits[key] == value
                    for key, value in expected_limits.items()))
