"""Manual JSON candidate truths, isolated execution and complete certificates.

Expected bytes are authored here, never generated by the trusted formatter or
the candidate. Invalid JSON reaches the candidate directly: admission and
oracle failures cannot stand in for a producer's explicit rejection.
"""
